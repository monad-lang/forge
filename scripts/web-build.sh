#!/usr/bin/env bash
# Build the forge web demo into target/web/: app.wasm, the generated loader
# (web.js), the host runtime (web_runtime.js, float_format.js) and the page
# (web/index.html, web/forge-floor.png). Used by web-serve.sh (browser) and
# web-smoke.sh (Node, stub GL).
#
#   devenv shell -- scripts/web-build.sh
#   MONAD_SRC=/path/to/monad scripts/web-build.sh
#
# The web host JS is NOT shipped with the toolchain or with the `web_wasm`
# git dependency, so it comes from a monad checkout (`MONAD_SRC`, default
# `../monad`), read with `git show` at the SAME rev `mote.toml` pins for
# `web_wasm` -- the JS must match the externs the wasm was built against.
# `web.js` is generated by that checkout's `scripts/gen-web-js.sh`, which
# builds from its working tree, so the script refuses to run when the
# checkout's web files have drifted from the pin.
#
# The wasm link needs an unwrapped clang (`MONAD_WEB_CC`, set by devenv.nix)
# and wasm-ld (`lld`), so run it inside `devenv shell`.
set -euo pipefail

root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
monad_src="${MONAD_SRC:-$root/../monad}"
monad_bin="${MONAD:-monad}"
out="$root/target/web"

rev="$(sed -n 's/^rev = "\([0-9a-f]*\)"$/\1/p' "$root/mote.toml" | head -n 1)"
[ -n "$rev" ] || { echo "web-build: no web_wasm rev in mote.toml" >&2; exit 1; }
[ -d "$monad_src/.git" ] \
    || { echo "web-build: no monad checkout at $monad_src (set MONAD_SRC)" >&2; exit 1; }
git -C "$monad_src" cat-file -e "${rev}^{commit}" 2>/dev/null \
    || { echo "web-build: $monad_src does not have $rev (git fetch there)" >&2; exit 1; }
if ! git -C "$monad_src" diff --quiet "$rev" -- wasm/web motes/web_wasm motes/jsgen \
        examples/gen_web_js.mo scripts/gen-web-js.sh; then
    echo "web-build: $monad_src's web files differ from the pinned $rev;" >&2
    echo "           check out $rev there (web.js is generated from the working tree)" >&2
    exit 1
fi

rm -rf "$out"
mkdir -p "$out"
for f in web_runtime.js float_format.js; do
    git -C "$monad_src" show "${rev}:wasm/web/$f" > "$out/$f"
done
# The generator is a monad-workspace example (`use web_wasm::...` resolves
# through that workspace), so the installed compiler must run FROM the
# checkout with MONAD_ROOT at it, or it reports `unknown variable
# 'Glue.loader'` (the workspace is found from the working directory).
monad_abs="$(command -v "$monad_bin")"
(cd "$monad_src" && MONAD_ROOT="$monad_src" MONAD="$monad_abs" scripts/gen-web-js.sh "$out/web.js")
cp "$root"/web/* "$out/"

# A member-scoped build reads `mote.lock` from the MEMBER's directory, not
# the workspace root that declares `web_wasm` (plans-monad
# 2026-11-17-forge-webgl-consumer-gaps G2). Give the two web members a copy
# of the root lock for the build only, so no second lock is committed to
# drift.
lock_copies=("$root/motes/forge-app/mote.lock" "$root/motes/forge-webgl/mote.lock")
cleanup() { rm -f "${lock_copies[@]}"; }
trap cleanup EXIT
for l in "${lock_copies[@]}"; do cp "$root/mote.lock" "$l"; done

echo "== build: forge-app-web for wasm32-unknown-unknown =="
(cd "$root" && "$monad_bin" build --target wasm32-unknown-unknown motes/forge-app \
    --bin forge-app-web -o "$out/app.wasm")
echo "web-build: wrote $out"
